"""Writes proxy/places.js from the app's offline places (Assets/Worldeck/Scripts/Core/Places.cs), so the relay's
worked examples and seed answers carry the same composed looks the app has.  python -I scripts/write-places.py"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "Assets", "Worldeck", "Scripts", "Core", "Places.cs")
OUT = os.path.join(HERE, "..", "places.js")
KEYS = ["top", "horizon", "fog", "ground", "ground_accent", "prop", "prop_accent", "emissive", "ambient"]

s = open(SRC, encoding="utf-8").read()
places = {}
for block in re.split(r"\n            new Place\n", s)[1:]:
    pid = re.search(r'Id = "([^"]+)"', block).group(1)
    look = {
        "name": re.search(r'Name = "([^"]+)"', block).group(1),
        "short": re.search(r'Short = "([^"]+)"', block).group(1),
        "horizon": re.search(r'Horizon = "([^"]+)"', block).group(1),
        "terrain": float(re.search(r"TerrainHeight = ([0-9.]+)f", block).group(1)),
        "sky": re.search(r'SkyFrom = "([^"]+)"', block).group(1),
        "ambience": re.search(r'Ambience = "([^"]+)"', block).group(1),
        "tint": float((re.search(r"Tint = ([0-9.]+)f", block) or re.match("()", "")).group(1) or 0),
        "scatter": re.findall(r'"([a-z_]+)"', re.search(r"Scatter = new\[\] \{([^}]*)\}", block).group(1)),
        "skins": {},
        "palette": dict(zip(KEYS, re.findall(r'"(#[0-9A-Fa-f]{6})"', re.search(r"Palette = P\(([^)]*)\)", block).group(1)))),
    }
    sk = re.search(r"Skins = S\((.*?)\)\s*\n", block)
    if sk:
        for role, sid in re.findall(r'\(Role\.(\w+), "([a-z_]+)"\)', sk.group(1)):
            look["skins"][role.lower()] = sid
    places[pid] = look

js = ("// Generated by scripts/write-places.py from Assets/Worldeck/Scripts/Core/Places.cs. Do not edit by hand.\n"
      "// The app's offline places, as composed looks: the relay's worked examples and seed answers use them.\n\n"
      "export const PLACE_LOOKS = " + json.dumps(places, indent=2) + ";\n")
open(OUT, "w", encoding="utf-8", newline="\n").write(js)
print(f"{len(places)} places -> {os.path.normpath(OUT)}")
